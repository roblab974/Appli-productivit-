// PRNG déterministe : même graine → même ordre
function mulberry32(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Verset du jour (dateStr au format yyyy-MM-dd). Chaque verset passe une fois par cycle, puis un nouvel ordre est tiré. */
export function verseOfDay(dateStr: string): { text: string; author: string } {
  const n = VERSES.length;
  const day = Math.floor(new Date(dateStr + "T00:00:00Z").getTime() / 86400000);
  const cycle = Math.floor(day / n);
  const rand = mulberry32(cycle + 1);
  const order = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  const [text, ref] = VERSES[order[day % n]];
  return { text, author: ref };
}
